//! Generates the skeleton of a protocol file (see PROTOCOL.md) from a device
//! file plus read-only queries to the mouse. Everything only a person who
//! tested the mouse can know is left as TODO.

use crate::device::Mouse;
use std::fmt::Write;

pub const REPO: &str = "khaosdoctor/opensynapse";

pub fn generate(mouse: &Mouse) -> String {
    let def = &mouse.def;
    let profile = 0;
    let firmware = mouse.firmware().unwrap_or_else(|_| "unknown".into());
    let mut out = String::new();
    // writes to a String can't fail
    let mut w = |s: String| {
        let _ = writeln!(out, "{s}");
    };

    w(format!("# {} keymap protocol\n", def.name));
    w(format!(
        "Device: USB `{:04x}:{:04x}`, firmware {firmware}. Device file: [`{}.toml`](../{}.toml).\n",
        def.vid, def.pid, def.file, def.file
    ));
    w("> Generated by `opensynapse protocol` from the device file and read-only queries to the mouse. \
       Everything marked TODO needs someone who tested the mouse, see [PROTOCOL.md](../../PROTOCOL.md)."
        .into());
    w("\nHow it was found: TODO (probing on Linux, a USB capture of Synapse, ...)\n".into());

    w("## Transport\n".into());
    w(format!(
        "Interface {}, transaction id `0x{:02x}`. TODO: anything else that's different from the common frame in PROTOCOL.md.\n",
        def.interface, def.transaction_id
    ));

    w("## Button ids\n".into());
    w(format!("What each button does right now, read from profile {profile}. The defaults only if nobody remapped them.\n"));
    let header: Vec<String> = def.layers.iter().cloned().collect();
    w(format!("| Id | Button | {} |", header.join(" | ")));
    w(format!("|---|---|{}", "---|".repeat(def.layers.len())));
    for b in &def.buttons {
        let actions: Vec<String> = (0..def.layers.len() as u8)
            .map(|l| mouse.get_button(profile, b.id, l).map_or("?".into(), |a| format!("`{a}`")))
            .collect();
        w(format!("| `0x{:02x}` | {} | {} |", b.id, b.name, actions.join(" | ")));
    }

    w("\n## DPI\n".into());
    let dpi = mouse.dpi().map_or("?".into(), |(x, y)| format!("{x} x {y}"));
    let stages = mouse.dpi_stages().map_or("?".into(), |s| {
        let list: Vec<String> = s.stages.iter().map(u16::to_string).collect();
        format!("{} (active: {})", list.join(", "), s.active)
    });
    w(format!("Current DPI {dpi}, stages {stages}, max {} from the device file.\n", def.dpi_max));
    w("TODO: say if the DPI commands are different from the Naga's.\n".into());

    w("## Action encoding\n".into());
    w("TODO: which action types you verified on this mouse (pressed the button and saw it work), and any that \
       differ from [the Naga's](razer-naga-left-handed-2020.md#action-encoding).\n"
        .into());

    w("## Unknowns\n".into());
    w("TODO: what you saw but couldn't explain, and what you didn't try.".into());
    out
}

/// Issue body for `protocol send`: the protocol file plus the device file.
pub fn issue(protocol: &str, mouse: &Mouse) -> (String, String) {
    let def = &mouse.def;
    let title = format!("Device support: {} ({:04x}:{:04x})", def.name, def.vid, def.pid);
    let body = format!(
        "{protocol}\n\n## Device file (`devices/{}.toml`)\n\n```toml\n{}\n```\n\n_Sent with `opensynapse protocol send`._\n",
        def.file,
        def.source.trim_end()
    );
    (title, body)
}
